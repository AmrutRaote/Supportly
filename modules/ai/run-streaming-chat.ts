import { run } from "@openai/agents";
import prisma from "@/lib/db";
import { messageToInput } from "./message-to-input";
import { SupportContext } from "./context";
import { triageAgent } from "./agents/triage-agent";
import { MESSAGE_ROLE } from "@/lib/generated/prisma/enums";


// saves the user's raw text to the database
async function saveUserMessage(conversationId: string, content: string, userId: string) {
  const user = await prisma.user.update({
    where: { id: userId },
    data: { messageCount: { increment: 1 } }
  });

  await prisma.message.create({
    data: {
      conversationId,
      content,
      role: "USER",
    },
  });

  return user;
}

async function saveAssistantMessage(
  conversationId: string,
  content: string,
  activeAgentName: string | null,
  toolsUsed: string[],
) {
  await prisma.message.create({
    data: {
      conversationId,
      content,
      role: MESSAGE_ROLE.ASSISTANT,
      agentName: activeAgentName,
      toolsUsed 
    },
  });

  await prisma.conversation.update({
    where: { id: conversationId },
    data: { updatedAt: new Date() },
  });
}

async function getConversationMessages(conversationId: string) {
  return prisma.message.findMany({
    where: { conversationId },
    orderBy: { createdAt: "asc" },
  });
}

type ChatStreamEvent = 
  | { type: "agent";  name: string}
  | { type: "tool";  name: string}
  | { type: "text";  delta: string}

function getToolName(item: {
  type?: string;
  rawItem?: { type?: string; name?: string };
}) {
  if (
    item.type === "tool_call_item" &&
    item.rawItem?.type === "function_call" &&
    item.rawItem.name
  ) {
    return item.rawItem.name;
  }

  return null;
}
function encodeEvent(event: ChatStreamEvent) {
  return new TextEncoder().encode(`${JSON.stringify(event)}\n`)
}


// runStreamingSupportChat acts as a middleman between the @openai/agents SDK and your Next.js API route
export async function runStreamingSupportChat(
  conversationId: string,
  userMessage: string,
  context: SupportContext,
) {
  const user = await saveUserMessage(conversationId, userMessage, context.userId);

  if (user.messageCount > 10) {
    const friendlyMessage = "Whoops! You've officially hit your 10-message limit. These AI tokens don't grow on trees, and my GPU landlord is demanding rent! Have a great day! 👋";
    return new ReadableStream<Uint8Array>({
      async start(controller) {
        try {
          controller.enqueue(encodeEvent({ type: "agent", name: "System" }));
          
          // Split message into chunks for a nice typing effect
          const words = friendlyMessage.split(" ");
          for (let i = 0; i < words.length; i++) {
            controller.enqueue(encodeEvent({ type: "text", delta: words[i] + (i === words.length - 1 ? "" : " ") }));
            await new Promise((resolve) => setTimeout(resolve, 50)); // tiny delay for animation
          }
          
          await saveAssistantMessage(conversationId, friendlyMessage, "System", []);
          controller.close();
        } catch (error) {
          controller.error(error);
        }
      }
    });
  }

  const messages = await getConversationMessages(conversationId);

  // start the process using our triageAgent and pass the formatted chat history (messageToInput), and we turn on stream: true so OpenAI sends us the AI's thoughts piece-by-piece as they are generated
  const agentStream = await run(triageAgent, messageToInput(messages), {
    stream: true,
    context
  });

  let assistantReply = "";
  let activeAgentName: string | null = triageAgent.name
  const toolsUsed: string[] = []

  // ReadableStream acts as an open pipe to the user's browser
  return new ReadableStream<Uint8Array>({
    async start(controller) {
      try {
        // Before the AI even starts talking, we push our first event down the pipe telling the 
        // frontend that the "Support Triage" agent is active, so the UI can immediately display the agent's badge. 
        // encodeEvent converts our JSON object into the raw bytes (NDJSON) the browser expects
        if (activeAgentName) {
          controller.enqueue(
            encodeEvent({type: "agent", name:activeAgentName})
          )
        }

        // start a loop that continuously listens to the agentStream coming from OpenAI
        for await (const event of agentStream) {
          // event from OpenAI indicates that the AI has decided to hand off the task
          if (event.type === "agent_updated_stream_event") {
            activeAgentName = event.agent.name
            controller.enqueue(
              encodeEvent({ type: "agent", name: activeAgentName})
            )
          }
          
          //event is raw text generated by the AI model (a "delta", which is usually just a few letters or a word), 
          // we append those letters to our massive assistantReply string
          if (event.type === "raw_model_stream_event" && event.data.type == "output_text_delta") {
            const delta = event.data.delta
            assistantReply += delta;
            controller.enqueue(
              encodeEvent({ type: "text", delta: delta})
            )
          }

          // helper function to check if the event is the AI calling a tool (like get_order_status)
          const toolName = getToolName(event as any);
          if (toolName) {
            toolsUsed.push(toolName);
            controller.enqueue(encodeEvent({ type: "tool", name: toolName }));
          }
        }

        // wait for a final signal from OpenAI guaranteeing that the AI has completely finished generating its response
        await agentStream.completed
        await saveAssistantMessage(conversationId, assistantReply, activeAgentName, toolsUsed)
        controller.close()
      } catch (error) {
        controller.error(error);
      }
    },
  });
}

export async function readTextStream(
  response: Response,
  onUpdate: (fullText: string) => void,
) {
  if (!response.body) {
    throw new Error("No response stream");
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let fullText = "";

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;

    fullText += decoder.decode(value, { stream: true });
    onUpdate(fullText);
  }

  return fullText;
}
